#!/usr/bin/env node
// Generates app/src/generated/inline-data.ts with the content JSON, figures,
// and (optionally) videos embedded as data URIs, for the self-contained
// preview build. Pure packaging — no content is authored here.
//
// Usage: node scripts/make-inline-data.mjs [--no-video]
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = join(root, "app", "public");
const noVideo = process.argv.includes("--no-video");

const content = readFileSync(join(pub, "content", "chapter2_section1.json"), "utf8");
const videos = readFileSync(join(pub, "content", "videos.json"), "utf8");

const figures = {};
for (const f of readdirSync(join(pub, "media", "figures"))) {
  const b64 = readFileSync(join(pub, "media", "figures", f)).toString("base64");
  figures[f] = `data:image/png;base64,${b64}`;
}

const media = {};
if (!noVideo) {
  for (const f of readdirSync(join(pub, "media", "videos"))) {
    const b64 = readFileSync(join(pub, "media", "videos", f)).toString("base64");
    media[`/media/videos/${f}`] = `data:video/mp4;base64,${b64}`;
  }
}

const out = `// GENERATED by scripts/make-inline-data.mjs — do not edit or commit.
import type { Content, VideoRegistry } from "../lib/content";

export const available = true;
export const content: Content = JSON.parse(${JSON.stringify(content)});
export const videos: VideoRegistry = JSON.parse(${JSON.stringify(videos)});
export const figures: Record<string, string> = ${JSON.stringify(figures)};
export const media: Record<string, string> = ${JSON.stringify(media)};
`;

writeFileSync(join(root, "app", "src", "generated", "inline-data.ts"), out);
const mb = (out.length / 1024 / 1024).toFixed(1);
console.log(`wrote inline-data.ts (${mb} MB, video ${noVideo ? "excluded" : "included"})`);
